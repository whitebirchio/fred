// Custom Worker entrypoint (docs/AUTH.md).
//
// Cloudflare Access authenticates at the edge, so an unauthorised request
// should never arrive here at all. This wrapper independently proves that it
// didn't: it verifies the Access token before handing anything to Next.js, so
// the app stays closed if Access is ever switched off, or if a route or custom
// domain is added later without a policy attached.
//
// Why here rather than Next's `proxy.ts`: Next 16 runs Proxy on the Node
// runtime only (the `runtime` config option throws), and OpenNext cannot
// bundle Node middleware for Workers. Wrapping the entrypoint is also strictly
// broader — it covers server actions, route handlers and assets, not just
// rendered routes.
//
// `wrangler.jsonc` points `main` here; `.open-next/worker.js` is generated by
// `opennextjs-cloudflare build` and does not exist until then.
import { default as handler } from "./.open-next/worker.js";
import {
  IDENTITY_HEADER,
  accessConfig,
  authMode,
  readAccessToken,
  verifyAccessJwt,
} from "./src/lib/access";

const plain = (body: string, status: number) =>
  new Response(body, {
    status,
    headers: { "content-type": "text/plain; charset=utf-8" },
  });

const worker = {
  async fetch(request: Request, env: Record<string, unknown>, ctx: unknown) {
    // Access's own login/logout endpoints are handled by Cloudflare in front of
    // the Worker; never gate them, or signing in could not complete.
    if (new URL(request.url).pathname.startsWith("/cdn-cgi/")) {
      return handler.fetch(request, env, ctx);
    }

    const mode = authMode(env);

    if (mode === "misconfigured") {
      return plain(
        "Cloudflare Access is not configured.\n\n" +
          "Fred will not serve financial data it cannot prove is being\n" +
          "requested by an authorised user. Set both secrets and redeploy:\n\n" +
          "  npx wrangler secret put CF_ACCESS_TEAM_DOMAIN\n" +
          "  npx wrangler secret put CF_ACCESS_AUD\n\n" +
          "See docs/AUTH.md.",
        500,
      );
    }

    // The identity header is derived state: drop anything inbound so a client
    // cannot assert an identity just by sending the header itself.
    const headers = new Headers(request.headers);
    headers.delete(IDENTITY_HEADER);

    if (mode === "enforce") {
      const cfg = accessConfig(env)!;
      const result = await verifyAccessJwt(readAccessToken(request), cfg);
      if (!result.ok) {
        // 401 rather than a redirect: Access owns the login flow and would
        // already have redirected a real browser. Reaching here means the
        // request bypassed or outlived it.
        return plain(`Not authorised: ${result.reason}.`, 401);
      }
      if (result.email) headers.set(IDENTITY_HEADER, result.email);
    }

    return handler.fetch(new Request(request, { headers }), env, ctx);
  },
};

export default worker;
